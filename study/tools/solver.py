"""Solve a book exercise with sympy where it is mechanical, and check the book's answer.

A problem notebook (study/notebooks, generated by notebooks.py) calls `attempt`
for every exercise. It reads the exercise's LaTeX as the converter wrote it,
decides whether the exercise is one sympy can do on its own -- a bare expression
or equation under an instruction such as "simplify", "evaluate", "solve" or
"factor", possibly as lettered parts ⓐ ⓑ ... -- and if so parses the math
(sympy's LaTeX parser), computes the answer, and compares it with the book's
answer (the answer key covers the odd-numbered exercises). The result's status:

- CHECKED   -- computed, and equal to the book's answer;
- MISMATCH  -- computed, but different from the book's answer (flagged for review:
               the parse, the book, or the instruction was misread);
- COMPUTED  -- computed; the book gives no answer, so it is unchecked until reviewed;
- MANUAL    -- not mechanical (a word problem, a graph, an explanation, a parse
               failure): restated only, for a person to solve and review.
"""

from __future__ import annotations

import dataclasses
import re
from typing import Any, TypeAlias

import sympy
from sympy.parsing.latex import parse_latex

# A parsed sympy value (expression, relational, set, tuple of parts).
Value: TypeAlias = Any

CHECKED: str = "checked"
MISMATCH: str = "mismatch"
COMPUTED: str = "computed"
MANUAL: str = "manual"

PART_MARK: re.Pattern[str] = re.compile(r"[ⓐⓑⓒⓓⓔⓕⓖⓗ]")
MATH: re.Pattern[str] = re.compile(r"\$([^$]+)\$")
# Words that may surround a bare expression without changing the task.
FILLER: set[str] = {
    "simplify",
    "evaluate",
    "solve",
    "find",
    "factor",
    "add",
    "subtract",
    "multiply",
    "divide",
    "the",
    "sum",
    "difference",
    "product",
    "quotient",
    "expression",
    "each",
    "check",
    "and",
    "or",
    "for",
    "of",
    "write",
    "as",
    "a",
    "an",
    "in",
    "terms",
    "fraction",
    "decimal",
    "number",
    "equation",
    "expand",
    "combine",
    "like",
    "terms",
    "using",
    "distributive",
    "property",
}
# "find" is not a task on its own (find the slope, the opposite, the factors ...).
TASKS: tuple[str, ...] = (
    "factor",
    "solve",
    "simplify",
    "evaluate",
    "multiply",
    "divide",
    "add",
    "subtract",
    "combine",
    "expand",
    "translate",
)


@dataclasses.dataclass
class Attempt:
    """What `attempt` found for one exercise."""

    status: str
    task: str = ""
    parts: list[str] = dataclasses.field(default_factory=list)  # the math, per part
    computed: list[Value] = dataclasses.field(default_factory=list)
    expected: list[Value] = dataclasses.field(default_factory=list)
    note: str = ""

    def show(self) -> str:
        """A plain-text report for the notebook cell output."""
        lines: list[str] = [
            "status: %s%s" % (self.status, " (%s)" % self.note if self.note else "")
        ]
        index: int
        value: Value
        for index, value in enumerate(self.computed):
            label: str = "" if len(self.computed) == 1 else "(%s) " % "abcdefgh"[index]
            lines.append(
                "%s%s %s  ->  %s" % (label, self.task, self.parts[index], sympy.sstr(value))
            )
            if index < len(self.expected):
                lines.append(
                    "%s   book answer: %s" % (" " * len(label), sympy.sstr(self.expected[index]))
                )
        return "\n".join(lines)


def clean(tex: str) -> str:
    """Normalize converter LaTeX to what sympy's LaTeX parser reads.

    >>> clean(r"\\,23r+14s+9r+(-15s).")
    '23r+14s+9r+(-15s)'
    >>> clean(r"32\\emph{r} $-$ \\emph{s}")
    '32r - s'
    """
    text: str = tex.replace("−", "-").replace("–", "-").replace("$", "")
    text = re.sub(r"\\(?:emph|textit|textbf|mathit|mathrm|text)\{([^{}]*)\}", r"\1", text)
    text = re.sub(r"\\[,;!:]|\\left|\\right|\\displaystyle|\\phantom\{[^}]*\}", "", text)
    text = text.replace("\\%", "/100").replace("\\le ", "\\leq ").replace("\\ge ", "\\geq ")
    text = re.sub(r"\\(?:label|cref|ref)\{[^}]*\}", "", text)
    while re.search(r"\d,\d{3}(?!\d)", text):  # 30,000,000 -> 30000000
        text = re.sub(r"(\d),(\d{3})(?!\d)", r"\1\2", text)
    # A mixed number 2\frac{4}{9} is 2 + 4/9, not 2 * 4/9.
    text = re.sub(r"(?<![\d.])(\d+)\s*\\frac\{(\d+)\}\{(\d+)\}", r"(\1+\\frac{\2}{\3})", text)
    # A letter before "(" multiplies (10u(3u - 1)); sympy would read a function call.
    text = re.sub(r"(?<![\\a-zA-Z])([a-zA-Z])\s*\(", r"\1\\cdot(", text)
    return text.strip().rstrip(".,;:?").strip()


def parse(tex: str) -> Value:
    """Parse one math string (antlr backend, then lark); ValueError if neither can."""
    text: str = clean(tex)
    if not text or re.search(r"\\(?:underline|_|square|text|quad|begin)|_\{?\s*\}|\?", text):
        raise ValueError("not a parseable expression: %r" % tex)
    backend: str
    for backend in ("antlr", "lark"):
        try:
            value: Value = parse_latex(text, backend=backend)
        except Exception:  # noqa: BLE001 -- either backend may reject; try the next
            continue
        if value is not None:
            return value
    raise ValueError("sympy cannot parse %r" % text)


def positive(value: Value) -> Value:
    """The value with every variable taken positive, as the books do when they
    simplify (sqrt(y^2) = y). Not for equations: their unknowns may be negative."""
    if not isinstance(value, sympy.Basic):
        return value
    return value.subs({v: sympy.Symbol(str(v), positive=True) for v in value.free_symbols})


def task_of(instruction: str, problem: str) -> str:
    """The verb that says what to do: the problem's own lead word, or the instruction's."""
    lead: re.Match[str] | None = re.match(r"\s*([A-Za-z]+)\s*:", problem)
    words: list[str] = ([lead.group(1).lower()] if lead else []) + instruction.lower().split()
    word: str
    for word in words:
        if word in TASKS:
            return word
    return ""


def bare_parts(problem: str) -> list[str] | None:
    """The math of a problem that is only math (one expression, or lettered parts of
    one expression each) with nothing but filler words around it; else None."""
    pieces: list[str] = [p for p in PART_MARK.split(problem)]
    texts: list[str] = pieces[1:] if len(pieces) > 1 else pieces
    lead: str = pieces[0] if len(pieces) > 1 else ""
    if lead and not set(re.findall(r"[a-z]+", MATH.sub(" ", lead).lower())) <= FILLER:
        return None
    parts: list[str] = []
    text: str
    for text in texts:
        found: list[str] = MATH.findall(text)
        words: set[str] = set(re.findall(r"[a-z]+", MATH.sub(" ", text).lower())) - {
            "item",
            "begin",
            "end",
            "itemize",
            "emph",
            "text",
        }
        if len(found) != 1 or not words <= FILLER:
            return None
        parts.append(found[0])
    return parts or None


def answer_parts(answer: str, count: int) -> list[str] | None:
    """The book answer's text per part (None when the counts differ)."""
    pieces: list[str] = [p for p in PART_MARK.split(answer)]
    texts: list[str] = pieces[1:] if len(pieces) > 1 else pieces
    texts = [re.sub(r"\\(?:begin|end)\{itemize\}|\\item\[\]", " ", t).strip() for t in texts]
    return texts if len(texts) == count and all(texts) else None


def compute(task: str, value: Value) -> Value:
    """Carry out the task on a parsed value."""
    if value is sympy.true or value is sympy.false:
        raise ValueError("a statement, not an expression")
    if isinstance(value, sympy.Equality):
        symbols: list[sympy.Basic] = sorted(value.free_symbols, key=str)
        if len(symbols) != 1:
            raise ValueError("an equation in %d unknowns" % len(symbols))
        return sympy.FiniteSet(
            *(sympy.nsimplify(r, rational=True) for r in sympy.solve(value, symbols[0]))
        )
    if isinstance(value, sympy.core.relational.Relational):
        symbols = sorted(value.free_symbols, key=str)
        if len(symbols) != 1:
            raise ValueError("an inequality in %d unknowns" % len(symbols))
        return sympy.solveset(value, symbols[0], sympy.S.Reals)
    if not isinstance(value, sympy.Expr):
        raise ValueError("not an expression")
    match task:
        case "factor":
            return sympy.factor(positive(value))
        case "solve":
            raise ValueError("solve without an equation")
        case _ if value.free_symbols:
            return sympy.expand(sympy.simplify(positive(value)))
        case _:
            return sympy.nsimplify(sympy.simplify(value), rational=True)


def expected_value(text: str, task: str) -> Value:
    """Parse a book answer; `x = 5` is the solution set {5}, `x > 3` an interval."""
    if "undefined" in text:
        return sympy.zoo
    if "not a real number" in text:
        return sympy.nan  # matched by any non-real computed value (see same)
    if re.search(r"\d\s*R\s*\d", text):
        raise ValueError("a quotient with a remainder")
    if "=" in text and not re.search(r"[a-z]", text.split("=")[0].replace("emph", "")):
        text = text.rsplit("=", 1)[1]  # "25+74=99": the book wrote the sum out
    value: Value = parse(text)
    if isinstance(value, sympy.Equality) and not value.lhs.free_symbols:
        return value.rhs  # "5,837+695=6,532": the book wrote the sum out
    if isinstance(value, sympy.Equality) and isinstance(value.lhs, sympy.Symbol):
        return sympy.FiniteSet(value.rhs)
    if isinstance(value, sympy.core.relational.Relational) and len(value.free_symbols) == 1:
        return sympy.solveset(value, next(iter(value.free_symbols)), sympy.S.Reals)
    if task == "solve" and isinstance(value, sympy.Expr) and not value.free_symbols:
        return sympy.FiniteSet(value)
    return value


def decimals(value: Value) -> int | None:
    """Decimal places of a Float answer (the book rounded to them), else None."""
    if isinstance(value, sympy.Float):
        digits: str = sympy.sstr(value).split(".")[-1].rstrip("0")
        return len(digits)
    return None


def same(computed: Value, expected: Value, task: str) -> bool:
    """Whether a computed answer matches the book's (rounding to the book's places)."""
    try:
        if computed is sympy.zoo or expected is sympy.zoo:
            return computed is expected or computed is sympy.nan
        if expected is sympy.nan:
            return isinstance(computed, sympy.Expr) and not computed.is_real
        if isinstance(computed, sympy.FiniteSet) and isinstance(expected, sympy.FiniteSet):
            return len(computed) == len(expected) and all(
                any(same(c, e, "") for e in expected.args) for c in computed.args
            )
        if isinstance(computed, sympy.Set) or isinstance(expected, sympy.Set):
            return bool(sympy.simplify(computed) == sympy.simplify(expected))
        if task == "factor" and isinstance(expected, sympy.Expr):
            return bool(
                sympy.simplify(positive(computed) - positive(expected)) == 0
                and sympy.factor(positive(expected)) == computed
            )
        places: int | None = decimals(expected)
        if places is not None and not computed.free_symbols:
            return abs(float(computed) - float(expected)) <= 0.5 * 10 ** (-places) + 1e-9
        return bool(sympy.simplify(positive(computed) - positive(expected)) == 0)
    except Exception:  # noqa: BLE001 -- incomparable values are simply not a match
        return False


def attempt(instruction: str, problem: str, answer: str) -> Attempt:
    """Try one exercise; see the module docstring for the statuses."""
    task: str = task_of(instruction, problem)
    parts: list[str] | None = bare_parts(problem)
    # Finding a GCF of a list is not factoring an expression.
    listing: bool = "greatest common factor of" in instruction or (
        task == "factor" and "find" in instruction.split()[:1]
    )
    if not task or task == "translate" or parts is None or listing:
        return Attempt(MANUAL, task=task, note="not a bare expression or equation")
    try:
        computed: list[Value] = [compute(task, parse(p)) for p in parts]
    except Exception as error:  # noqa: BLE001 -- any failure means a person must do it
        return Attempt(MANUAL, task=task, parts=parts, note=str(error)[:80])
    result: Attempt = Attempt(COMPUTED, task=task, parts=parts, computed=computed)
    if not answer.strip():
        result.note = "no book answer: unchecked until reviewed"
        return result
    texts: list[str] | None = answer_parts(answer, len(parts))
    try:
        if texts is None:
            raise ValueError("the book answer has a different number of parts")
        result.expected = [expected_value(t, task) for t in texts]
    except Exception as error:  # noqa: BLE001
        result.note = "book answer not parsed: %s" % str(error)[:60]
        return result
    matches: bool = all(
        same(c, e, task) for c, e in zip(result.computed, result.expected, strict=True)
    )
    result.status = CHECKED if matches else MISMATCH
    return result


def plottable(value: Value) -> bool:
    """An equation in x and/or y only (a line or curve to graph).

    >>> [plottable(parse(t)) for t in ("y=2x+1", "y=-2", "x=3", "a+1=2", "3+4")]
    [True, True, True, False, False]
    """
    names: set[str] = {str(s) for s in getattr(value, "free_symbols", set())}
    return isinstance(value, sympy.Equality) and bool(names) and names <= {"x", "y"}


def graph_target(problem: str) -> Value | None:
    """The x-y equation a graphing exercise asks for, if the problem is one."""
    found: list[str] = MATH.findall(problem)
    if len(found) != 1:
        return None
    try:
        value: Value = parse(found[0])
    except ValueError:
        return None
    return value if plottable(value) else None
