#!/usr/bin/env python3
r"""Normalize a Trench master .tex to build under osbook.cls (impo, trench family).

Phase 2 of tasks/add-trench-differential-equations-book.md. A deterministic
LaTeX->LaTeX transform: replace the Trench `book`/dvips preamble with an osbook
preamble (loading osbook-envs + the trench-osbook shim + the book metadata), and
drop the manual `\setcounter{chapter}{N}` lines (osbook's \chapter auto-numbers).
The document body is otherwise unchanged -- aesthetics only, no mathematical
content is touched. Front matter / license is Phase 4; EPS->PDF is Phase 3.

Reads the PRISTINE master and writes a sibling `<stem>-osbook.tex`, so it is
re-runnable and never mutates the fetched source.

Paths are relative to the script or an explicit argument -- never container-absolute.
Run:  python3 tools/normalize_master.py [path/to/MASTER.tex]
      (default: ../checkout/TRENCH_DIFFEQ.tex, relative to this script)
"""
from __future__ import annotations

import os
import re
import subprocess
import sys
from pathlib import Path

