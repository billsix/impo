def about_this_edition() -> str:
    r"""The "About This Edition" front-matter colophon for the trench book: formatted
    by Bill Six, the impo toolchain + build commit SHA + date, and a pointer to the
    CC BY-NC-SA 3.0 license page. `\chapter*` (NOT `\chapter`) because it sits after
    `\OSfrontmatter`'s `\mainmatter`, so a plain `\chapter` would step the counter and
    shift "Chapter 1"; starred = unnumbered + no increment, `\addcontentsline` keeps it
    in the TOC. The impo commit SHA + date come from IMPO_COMMIT / IMPO_BUILD_DATE, or,
    since this runs on the host in the impo repo, fall back to `git rev-parse HEAD`."""
    sha: str = os.environ.get("IMPO_COMMIT", "").strip()
    if not sha:
        try:
            sha = subprocess.check_output(
                ["git", "rev-parse", "HEAD"], cwd=str(Path(__file__).resolve().parent)
            ).decode().strip()
        except (OSError, subprocess.CalledProcessError):
            sha = ""
    date: str = os.environ.get("IMPO_BUILD_DATE", "").strip()
    if sha:
        built: str = ", built from commit \\texttt{%s}" % sha
        if date:
            built += " on %s" % date
    else:
        built = " (a local development build)"
    return (
        "\\chapter*{About This Edition}\n"
        "\\addcontentsline{toc}{chapter}{About This Edition}\n"
        "This edition of \\emph{Elementary Differential Equations} by William F. Trench "
        "was formatted by William Emerison Six (``Bill~Six'') using the \\emph{impo} "
        "toolchain (\\href{https://github.com/billsix/impo}{github.com/billsix/impo})%s.\n\n"
        "\\medskip\\noindent The text and figures are \\textcopyright{} William F. Trench, "
        "licensed under a Creative Commons Attribution-NonCommercial-ShareAlike 3.0 "
        "Unported License (CC~BY-NC-SA~3.0); see the license page above. The impo "
        "toolchain and this LaTeX formatting are \\textcopyright{} William Emerison Six, "
        "released under the MIT License.\n\n" % built
    )


def normalize(text: str) -> str:
    # 1. Cut point = the Preface bookmark. Everything BEFORE it (the book/dvips
    #    preamble + hand title/license/dedication/contents) is replaced by the
    #    osbook preamble + \OSfrontmatter; the Preface and all chapters are kept.
    m: re.Match[str] | None = re.search(r"\\pdfbookmark\[0\]\{Preface\}", text)
    if m is None:
        raise SystemExit("normalize: Preface marker not found (front-matter cut point)")
    body: str = text[m.start():]
    # 2. Drop the manual chapter-counter setters (osbook \chapter auto-numbers).
    body = re.sub(r"^[ \t]*\\setcounter\{chapter\}\{\d+\}[ \t]*\n", "", body, flags=re.M)
    # 3. Body fixups:
    #    (a) \enlargethispage{1\in} -- \in is the math ∈ symbol, not a length unit;
    #        the author meant 1in.
    body = body.replace(r"\enlargethispage{1\in}", r"\enlargethispage{1in}")
    #    (b) Strip the EPS bounding box from every \includegraphics. Trench stamps
    #        the SAME bb (bb=-78 148 689 643) on every figure -- an artifact of the
    #        EPS/dvips pipeline. epstopdf already crops each PDF to its own real box
    #        at origin (0,0), so re-declaring a non-zero-origin bb OFFSETS the image
    #        (down/right, overlapping the caption). Remove bb= and let graphicx use
    #        each PDF's MediaBox; the width/height/keepaspectratio still size it.
    body = re.sub(r"bb\s*=\s*-?[\d.]+\s+-?[\d.]+\s+-?[\d.]+\s+-?[\d.]+\s*,?\s*", "", body)
    #    (c) Cap figure width at the text block. Trench sizes figures at 5.67in but
    #        the osbook measure is 5in, so wide figures overflowed the right margin
    #        (many Overfull \hbox). adjustbox's [export] `max width` key (loaded by
    #        the shim) constrains each figure to \linewidth while keeping smaller
    #        ones at their intended size.
    body = body.replace(r"\includegraphics[", r"\includegraphics[max width=\linewidth,")
    #    (d) `\l` in math is a source typo for `\ell` (ℓ): the author writes `\l`
    #        and `\ell` interchangeably in adjacent exercises, and `\l` (Polish ł) is
    #        invalid in math ("Missing character ł in cmmi10"). Replace a bare `\l`
    #        (not part of a longer control word like \ldots/\linewidth/\ll) with \ell.
    body = re.sub(r"\\l(?![a-zA-Z])", r"\\ell", body)
    # Insert the "About This Edition" colophon right after \OSfrontmatter (the last
    # line of OSBOOK_PREAMBLE), before the Preface -- the first front-matter unit.
    return OSBOOK_PREAMBLE + about_this_edition() + body


def main() -> None:
    default: Path = Path(__file__).resolve().parents[1] / "checkout" / "TRENCH_DIFFEQ.tex"
    src: Path = Path(sys.argv[1]) if len(sys.argv) > 1 else default
    if not src.exists():
        raise SystemExit(f"normalize: master not found: {src}")
    out: Path = src.with_name(src.stem + "-osbook.tex")
    out.write_text(normalize(src.read_text(encoding="utf-8")), encoding="utf-8")
    print(f"normalize: wrote {out}")


if __name__ == "__main__":
    main()
